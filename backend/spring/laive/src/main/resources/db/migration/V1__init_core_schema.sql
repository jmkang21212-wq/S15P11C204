    ON calendar_events (streamer_id, start_at)
    WHERE status = 'SCHEDULED' AND event_type = 'BROADCAST';

CREATE TRIGGER trg_calendar_events_updated_at
    BEFORE UPDATE ON calendar_events
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE calendar_events IS '방송/휴방 일정 (SC-04)';


