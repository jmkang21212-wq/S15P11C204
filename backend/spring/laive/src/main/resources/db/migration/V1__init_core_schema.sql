CREATE TABLE broadcast_sessions (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id         BIGINT       NOT NULL REFERENCES streamers (id)         ON DELETE CASCADE,
    platform_account_id BIGINT       NOT NULL REFERENCES platform_accounts (id) ON DELETE RESTRICT,
    calendar_event_id   BIGINT       REFERENCES calendar_events (id) ON DELETE SET NULL,
    title               VARCHAR(200) NOT NULL,
    category            VARCHAR(50),
    language            VARCHAR(10)  NOT NULL DEFAULT 'ko',
    thumbnail_url       VARCHAR(1024),                 -- API 1.5
    vod_url             VARCHAR(1024),                 -- API 1.5
    status              VARCHAR(20)  NOT NULL DEFAULT 'PREPARING',
    started_at          TIMESTAMPTZ  NOT NULL,
    ended_at            TIMESTAMPTZ,                   -- 진행 중인 방송은 NULL (API 1.5)
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_broadcast_sessions_status
        CHECK (status IN ('PREPARING', 'LIVE', 'ENDED', 'FAILED')),
    CONSTRAINT ck_broadcast_sessions_period
        CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_broadcast_sessions_ended_at
        CHECK (status <> 'ENDED' OR ended_at IS NOT NULL)
);

-- API 1.6 / 오류코드 SESSION_ALREADY_LIVE:
-- 한 스트리머는 동시에 하나의 진행 중 세션만 가질 수 있다.
-- 애플리케이션의 Redis 잠금과 별개로 DB 레벨에서도 강제한다.
CREATE UNIQUE INDEX ux_broadcast_sessions_single_active
    ON broadcast_sessions (streamer_id)
    WHERE status IN ('PREPARING', 'LIVE');

-- GET /broadcast-sessions (목록·페이징), 성장 리포트 집계
CREATE INDEX ix_broadcast_sessions_streamer_started
    ON broadcast_sessions (streamer_id, started_at DESC);

CREATE INDEX ix_broadcast_sessions_calendar_event_id
    ON broadcast_sessions (calendar_event_id)
    WHERE calendar_event_id IS NOT NULL;

CREATE TRIGGER trg_broadcast_sessions_updated_at
    BEFORE UPDATE ON broadcast_sessions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE  broadcast_sessions            IS '방송 분석 세션. 모든 실시간 데이터의 기준점';
COMMENT ON COLUMN broadcast_sessions.started_at IS '방송 시작 시각. transcripts/highlights의 startMs 기준점이다';


