    sent_at    TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_chat_messages PRIMARY KEY (id, sent_at)
);

-- API 11.5 하이라이트 채팅 리플레이:
-- 정렬 키가 (sent_at ASC, id ASC)이므로 커서 페이징을 인덱스만으로 처리한다.
CREATE INDEX ix_chat_messages_session_sent ON chat_messages (session_id, sent_at, id);

-- 시청자별 채팅 활동 집계 (viewer_scores.chat_score)
CREATE INDEX ix_chat_messages_viewer_sent ON chat_messages (viewer_id, sent_at DESC);

COMMENT ON TABLE chat_messages IS '방송 채팅 로그. V2에서 hypertable로 전환한다';


-- -----------------------------------------------------------------------------
-- TRANSCRIPTS : STT 결과
--
--   ERD 그대로 일반 테이블이다. hypertable로 만들지 않는다.
--   15초 청크 × 3시간 방송 = 세션당 약 700행이라 파티셔닝 이득이 거의 없는 반면,
--   hypertable로 만들면 파티션 키(절대 시각) 컬럼을 새로 넣어야 하고
--   risk_events / promises / report_segments 가 거는 FK 3개를 포기해야 한다.
--   (hypertable은 FK 참조 대상이 될 수 없다)
-- -----------------------------------------------------------------------------
CREATE TABLE transcripts (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT      NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    start_ms   BIGINT      NOT NULL,
    end_ms     BIGINT      NOT NULL,
    transcript TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- API 1.4: STT Callback 재시도 시 동일 청크 중복 방지
    CONSTRAINT uq_transcripts_session_range UNIQUE (session_id, start_ms, end_ms),
    CONSTRAINT ck_transcripts_start_ms CHECK (start_ms >= 0),
    CONSTRAINT ck_transcripts_range    CHECK (end_ms > start_ms)
);

-- 세션 전문 조회·리포트 생성 입력은 uq_transcripts_session_range
-- (session_id, start_ms, end_ms)의 선두 컬럼으로 커버되므로 별도 인덱스를 두지 않는다.

COMMENT ON TABLE transcripts IS 'STT 변환 결과. 세션당 수백 행 수준이라 일반 테이블로 둔다';


-- -----------------------------------------------------------------------------
-- RISK_EVENTS : 위험 발언 (FR-S-01)
--   세션당 수 건 수준이라 hypertable로 만들지 않는다.
-- -----------------------------------------------------------------------------
CREATE TABLE risk_events (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT      NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    transcript_id BIGINT      NOT NULL REFERENCES transcripts (id) ON DELETE CASCADE,
    risk_level    VARCHAR(10) NOT NULL,
    risk_category VARCHAR(30) NOT NULL,
    advice        TEXT,
    detected_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_risk_events_risk_level CHECK (risk_level IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_risk_events_risk_category
        CHECK (risk_category IN ('PROFANITY', 'POLITICS', 'DISCRIMINATION',
