-- -----------------------------------------------------------------------------
-- STREAMERS : 스트리머(회원)
-- -----------------------------------------------------------------------------
CREATE TABLE streamers (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(255),                    -- 소셜 전용 계정은 NULL (API 1.5)
    password_hash     VARCHAR(255),                    -- 소셜 전용 계정은 NULL (API 1.5)
    nickname          VARCHAR(50)  NOT NULL,
    profile_image_url VARCHAR(1024),
    bio               TEXT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_streamers_email UNIQUE (email),
    -- 대소문자만 다른 중복 가입을 막기 위해 애플리케이션에서 소문자로 정규화한 뒤 저장한다.
    CONSTRAINT ck_streamers_email_lowercase CHECK (email IS NULL OR email = lower(email))
);

CREATE TRIGGER trg_streamers_updated_at
    BEFORE UPDATE ON streamers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE  streamers                   IS '스트리머(회원) 기본 정보';
COMMENT ON COLUMN streamers.email             IS '로그인 이메일. 소셜 제공자가 이메일을 주지 않는 경우 NULL';
COMMENT ON COLUMN streamers.password_hash     IS 'BCrypt 등으로 해시한 비밀번호. 소셜 전용 계정은 NULL';


-- -----------------------------------------------------------------------------
-- AUTH_REFRESH_TOKENS : JWT Refresh Token (만료 14일)
-- -----------------------------------------------------------------------------
CREATE TABLE auth_refresh_tokens (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id BIGINT       NOT NULL REFERENCES streamers (id) ON DELETE CASCADE,
    token_hash  VARCHAR(255) NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ,                           -- 미폐기 토큰은 NULL (API 1.5)
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_auth_refresh_tokens_token_hash UNIQUE (token_hash)
);

-- 로그아웃·비밀번호 변경 시 "해당 스트리머의 유효 토큰 전체 폐기" 경로
CREATE INDEX ix_auth_refresh_tokens_active
    ON auth_refresh_tokens (streamer_id)
    WHERE revoked_at IS NULL;

-- 만료 토큰 정리 배치용
CREATE INDEX ix_auth_refresh_tokens_expires_at ON auth_refresh_tokens (expires_at);

COMMENT ON TABLE  auth_refresh_tokens            IS 'JWT Refresh Token. 원문이 아닌 해시를 저장한다';
COMMENT ON COLUMN auth_refresh_tokens.revoked_at IS '로그아웃 또는 비밀번호 변경으로 폐기된 시각';


