-- platform_accounts의 토큰 컬럼 → platform_account_credentials
CREATE OR REPLACE FUNCTION sync_platform_account_credential()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.access_token IS NULL THEN
        DELETE FROM platform_account_credentials WHERE platform_account_id = NEW.id;
        RETURN NEW;
    END IF;

    INSERT INTO platform_account_credentials (
        platform_account_id, auth_scheme, encrypted_credential_payload,
        access_expires_at, refresh_expires_at, scopes
    ) VALUES (
        NEW.id,
        'OAUTH2',
        jsonb_build_object('accessToken', NEW.access_token, 'refreshToken', NEW.refresh_token)::text,
        NEW.access_token_expires_at,
        NEW.refresh_token_expires_at,
        NEW.scope
    )
    ON CONFLICT (platform_account_id) DO UPDATE
       SET encrypted_credential_payload = EXCLUDED.encrypted_credential_payload,
           access_expires_at = EXCLUDED.access_expires_at,
           refresh_expires_at = EXCLUDED.refresh_expires_at,
           scopes = EXCLUDED.scopes,
           credential_version = platform_account_credentials.credential_version + 1;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_platform_accounts_sync_credential
    AFTER INSERT OR UPDATE OF access_token, refresh_token, access_token_expires_at,
                              refresh_token_expires_at, scope
    ON platform_accounts
    FOR EACH ROW EXECUTE FUNCTION sync_platform_account_credential();


-- broadcast_sessions 생성 → 대표 broadcast_platform_sessions 자식 한 행.
-- 새 서비스는 같은 유니크 키를 쓰므로 추가 플랫폼 자식을 붙이기 전에 이 행을
-- 그대로 재사용한다.
CREATE OR REPLACE FUNCTION ensure_representative_platform_session()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO broadcast_platform_sessions (
        broadcast_session_id, platform_account_id, status,
        started_at, ended_at, last_synced_at
    ) VALUES (
        NEW.id, NEW.platform_account_id, NEW.status,
        NEW.started_at, NEW.ended_at, COALESCE(NEW.ended_at, NEW.started_at)
    )
    ON CONFLICT (broadcast_session_id, platform_account_id) DO NOTHING;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_broadcast_sessions_ensure_platform_child
    AFTER INSERT ON broadcast_sessions
    FOR EACH ROW EXECUTE FUNCTION ensure_representative_platform_session();


-- calendar_events.platform_account_id → calendar_event_platform_accounts.
-- 새 버전은 이 트리거가 대표 계정을 반영한 뒤 배정 집합 전체를 교체한다.
CREATE OR REPLACE FUNCTION sync_calendar_event_primary_platform_account()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE'
       AND OLD.platform_account_id IS DISTINCT FROM NEW.platform_account_id
       AND OLD.platform_account_id IS NOT NULL THEN
        DELETE FROM calendar_event_platform_accounts
         WHERE calendar_event_id = NEW.id
           AND platform_account_id = OLD.platform_account_id;
    END IF;

    IF NEW.platform_account_id IS NOT NULL THEN
        INSERT INTO calendar_event_platform_accounts (
            calendar_event_id,
            platform_account_id
        ) VALUES (
            NEW.id,
            NEW.platform_account_id
        )
        ON CONFLICT DO NOTHING;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_calendar_event_primary_platform_account
    AFTER INSERT OR UPDATE OF platform_account_id ON calendar_events
    FOR EACH ROW
    EXECUTE FUNCTION sync_calendar_event_primary_platform_account();


