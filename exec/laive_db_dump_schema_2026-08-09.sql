-- =============================================================================
-- Streamer Risk Dictionary (AI/RISK_POLICY_SPEC.md)
--
-- 위험 발언의 기준은 방송 스타일마다 다르다. 욕설이 캐릭터인 스트리머에게 기본
-- 설정은 30초마다 경고를 띄우고, 경고가 흔해지면 스트리머는 경고를 보지 않게 된다.
-- 그 순간 정작 잡아야 할 발언도 같이 묻힌다.
--
--   BLOCK(금칙어) : 기본 사전에 없는 표기를 추가한다. 사전 히트는 LLM을 건너뛰고
--                   즉시 알림이므로, 스트리머가 "이건 무조건 잡아"라고 말한 것이 된다.
--   ALLOW(허용어) : 기본 사전에서 그 표기를 뺀다. 여기서 끝이 아니다 — 사전에서
--                   빠진 발화는 LLM으로 넘어가고, LLM은 자기 기준으로 그대로 잡는다.
--                   그래서 AI 서버는 이 목록을 LLM 프롬프트에도 함께 주입한다.
--                   한쪽만 하면 기능이 조용히 동작하지 않는다.
-- =============================================================================

CREATE TABLE streamer_risk_terms (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id BIGINT      NOT NULL REFERENCES streamers (id) ON DELETE CASCADE,
    kind        VARCHAR(10) NOT NULL,

    -- AI 서버의 정규화(app/detect/normalize.py)를 거친 표기.
    -- 매칭이 정규화된 문자열 위에서 일어나므로 저장도 같은 형태로 맞춘다.
    term        VARCHAR(40) NOT NULL,

    -- 사용자가 입력한 원문. 설정 화면에 보여줄 때 쓴다.
    -- 정규화된 term은 사람이 읽기 나쁘고, 자기가 뭘 등록했는지 알아보지 못한다.
    display     VARCHAR(40) NOT NULL,

    -- BLOCK만 사용한다. 경고에 severity가 필요한데(FRONTEND_API.md §4) 사전에
    -- 없던 표기라 기본 사전에서 물려받을 값이 없다. NULL이면 MEDIUM으로 본다.
    severity    VARCHAR(10),

    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- 같은 표기를 같은 종류로 두 번 등록하는 것만 막는다. BLOCK과 ALLOW에 같은
    -- 표기가 동시에 들어가는 것은 DB가 아니라 서비스 계층이 막는다 — 그쪽이
    -- "이미 허용어에 있습니다" 같은 설명을 돌려줄 수 있다.
    CONSTRAINT uq_srt_streamer_kind_term UNIQUE (streamer_id, kind, term),
    CONSTRAINT ck_srt_kind     CHECK (kind IN ('BLOCK', 'ALLOW')),
    CONSTRAINT ck_srt_severity CHECK (severity IS NULL OR severity IN ('LOW', 'MEDIUM', 'HIGH')),
    -- 두 글자 미만은 다른 단어에 묻힌다(terms.yaml 설계 원칙 3: 스발←가스발전).
    -- 서비스 계층 검증과 중복이지만, 직접 INSERT하는 경로까지 막아 둔다.
    CONSTRAINT ck_srt_term_length CHECK (char_length(term) >= 2)
);

-- 티켓 발급과 pub/sub 발행이 스트리머 단위로 전량 조회한다. 종류별로 나눠 담아야
-- 하므로 kind를 뒤에 붙인다.
CREATE INDEX ix_srt_streamer ON streamer_risk_terms (streamer_id, kind);

COMMENT ON TABLE  streamer_risk_terms          IS '스트리머 개인 사전. BLOCK=금칙어(사전에 추가), ALLOW=허용어(사전에서 제거 + LLM 프롬프트 주입)';
COMMENT ON COLUMN streamer_risk_terms.term     IS 'AI 서버 정규화를 거친 표기. 매칭·중복 판정의 기준';
COMMENT ON COLUMN streamer_risk_terms.display  IS '사용자 입력 원문. 설정 화면 표시용';
COMMENT ON COLUMN streamer_risk_terms.severity IS 'BLOCK 전용. NULL이면 MEDIUM으로 본다';


