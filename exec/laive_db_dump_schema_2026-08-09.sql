-- -----------------------------------------------------------------------------
-- REPORTS : 세션 리포트
--
-- 감정을 비율이 아니라 8종 건수로 저장하는 이유
--   - 비율 8개를 NUMERIC(4,3)으로 저장하면 반올림 때문에 합이 1에서 최대
--     ±0.004까지 벌어진다. 건수는 나눗셈이 조회 시점에 일어나므로 합이 정확히 1이다.
--   - 성장 리포트가 여러 세션을 묶을 때 SUM(joy_count)/SUM(analyzed_chat)이 되어
--     채팅량 가중이 자동으로 걸린다. 세션별 비율을 평균하면 조용한 방송과
--     대박 방송이 같은 비중이 된다.
--   - analyzed_chat / total_chat이 곧 분류 커버리지이며 PARTIAL 판정 근거다.
-- -----------------------------------------------------------------------------
CREATE TABLE reports (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id       BIGINT      NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    status           VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',
    summary          TEXT,                              -- PROCESSING·요약 실패 시 NULL (API 1.5)
    avg_viewers      INT,
    peak_viewers     INT,
    total_chat       BIGINT,
    generated_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 집계가 완료되지 않은 PROCESSING 상태에서는 전부 NULL이다 (API 1.5).
    analyzed_chat    BIGINT,
    joy_count        BIGINT,
    excitement_count BIGINT,
    support_count    BIGINT,
    surprise_count   BIGINT,
    sadness_count    BIGINT,
    anger_count      BIGINT,
    confusion_count  BIGINT,
    neutral_count    BIGINT,

    -- API 1.4: 세션당 리포트 1개 보장
    CONSTRAINT uq_reports_session_id UNIQUE (session_id),
    CONSTRAINT ck_reports_status
        CHECK (status IN ('PROCESSING', 'COMPLETED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_reports_generated_at
        CHECK (status NOT IN ('COMPLETED', 'PARTIAL') OR generated_at IS NOT NULL),
    -- 아홉 컬럼은 전부 채워지거나 전부 NULL이어야 한다. 일부만 채워지면
    -- 합 검증이 NULL로 통과해버려 분모와 분자가 어긋난 채 저장된다.
    CONSTRAINT ck_reports_sentiment_presence CHECK (
        num_nulls(analyzed_chat, joy_count, excitement_count, support_count,
                  surprise_count, sadness_count, anger_count, confusion_count,
                  neutral_count) IN (0, 9)
    ),
    CONSTRAINT ck_reports_sentiment_sum CHECK (
        analyzed_chat IS NULL OR
        analyzed_chat = joy_count + excitement_count + support_count + surprise_count
                      + sadness_count + anger_count + confusion_count + neutral_count
    ),
    CONSTRAINT ck_reports_analyzed_chat CHECK (
        analyzed_chat IS NULL OR total_chat IS NULL OR analyzed_chat <= total_chat
    )
);

CREATE TRIGGER trg_reports_updated_at
    BEFORE UPDATE ON reports
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE  reports               IS '방송 종료 후 생성되는 세션 리포트 (SC-06)';
COMMENT ON COLUMN reports.status        IS 'PARTIAL: AI 요약은 실패했지만 집계 지표는 제공하는 상태 (API 11.1)';
COMMENT ON COLUMN reports.total_chat    IS '집계 컬럼. Spring이 원천 데이터로 계산하며 AI Callback 값으로 덮어쓰지 않는다';
COMMENT ON COLUMN reports.analyzed_chat IS 'sentiment_label이 붙은 채팅 수. total_chat과의 비가 분류 커버리지다';


CREATE TABLE report_insights (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT       NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
    title      VARCHAR(200) NOT NULL,
    content    TEXT         NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_report_insights_report_id ON report_insights (report_id);

COMMENT ON TABLE report_insights IS 'AI가 제안한 방송 개선 인사이트';


CREATE TABLE report_platform_metrics (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id           BIGINT       NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
    platform_session_id BIGINT       NOT NULL
        REFERENCES broadcast_platform_sessions (id) ON DELETE CASCADE,
    avg_viewers         INT,
    peak_viewers        INT,
    total_chat          BIGINT       NOT NULL DEFAULT 0,
    analyzed_chat       BIGINT       NOT NULL DEFAULT 0,
    joy_count           BIGINT       NOT NULL DEFAULT 0,
    excitement_count    BIGINT       NOT NULL DEFAULT 0,
    support_count       BIGINT       NOT NULL DEFAULT 0,
    surprise_count      BIGINT       NOT NULL DEFAULT 0,
    sadness_count       BIGINT       NOT NULL DEFAULT 0,
    anger_count         BIGINT       NOT NULL DEFAULT 0,
    confusion_count     BIGINT       NOT NULL DEFAULT 0,
    neutral_count       BIGINT       NOT NULL DEFAULT 0,
    broadcast_seconds   BIGINT       NOT NULL DEFAULT 0,
    viewer_coverage     NUMERIC(5,4),
    data_quality        VARCHAR(20)  NOT NULL DEFAULT 'COMPLETE',
    extra_metrics       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_report_platform_metrics UNIQUE (report_id, platform_session_id),
    CONSTRAINT ck_report_platform_metrics_quality CHECK (data_quality IN ('COMPLETE', 'PARTIAL')),
    CONSTRAINT ck_report_platform_metrics_coverage
        CHECK (viewer_coverage IS NULL OR viewer_coverage BETWEEN 0 AND 1),
    CONSTRAINT ck_report_platform_metrics_counts CHECK (
        total_chat >= 0 AND analyzed_chat >= 0 AND broadcast_seconds >= 0
        AND analyzed_chat = joy_count + excitement_count + support_count + surprise_count
                          + sadness_count + anger_count + confusion_count + neutral_count
    )
);

CREATE INDEX ix_report_platform_metrics_report ON report_platform_metrics (report_id);

COMMENT ON COLUMN report_platform_metrics.extra_metrics
    IS 'Provider-specific metrics not used by common growth calculations.';


-- -----------------------------------------------------------------------------
-- TRIGGERS : 리포트 앵커
--
-- 판정 알고리즘은 AI/chat-ai/HIGHLIGHT_SPEC.md이며 Spring이 자체 수행한다.
-- 구간이 확정될 때마다 한 행을 append한다.
--
-- 보관 정책을 걸지 않는 이유
--   트리거는 원본이 아니라 구간 요약이고, chat_messages가 90일에 삭제된 뒤
--   남겨야 할 것이 바로 그 요약이다. 세션당 수~수십 행이라 절약분도 없다.
--
-- hypertable로 만들지 않는 이유
--   세션당 수~수십 행이라 파티셔닝 이득이 없다. highlights가 이 테이블에 FK를
--   걸어야 하므로 hypertable이면 안 된다.
-- -----------------------------------------------------------------------------
CREATE TABLE triggers (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT       NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    trigger_type    VARCHAR(30)  NOT NULL,
    transcript_id   BIGINT       REFERENCES transcripts (id) ON DELETE SET NULL,

    -- 시각은 오프셋과 절대 시각을 둘 다 저장한다. transcripts는 오프셋으로,
    -- chat_messages는 절대 시각으로 조회하므로 소비자마다 필요한 형태가 다르다.
    -- 확정 시점의 Spring은 둘 다 알고 있고, 조회할 때마다 세션 시작 시각과
    -- 조인해 변환하면 오프셋과 절대 시각을 섞는 실수가 조인 지점마다 되살아난다.
    start_ms        BIGINT       NOT NULL,
    end_ms          BIGINT       NOT NULL,
    started_at      TIMESTAMPTZ  NOT NULL,
    ended_at        TIMESTAMPTZ  NOT NULL,

    -- 판정 지표. 상태기계가 구간을 확정했다는 것은 이 값들이 모두 계산됐다는
    -- 뜻이므로 NOT NULL이다. peak_z는 MAD 하한 ε=0.001에서 최대 약 675까지
    -- 나올 수 있어 정수부를 3자리 확보한다.
    peak_z          NUMERIC(6,3) NOT NULL,
    peak_engagement NUMERIC(5,4) NOT NULL,
    avg_viewers     INT          NOT NULL,
    chat_count      INT          NOT NULL,
    unique_chatters INT          NOT NULL,

    -- 구간 채팅의 라벨별 건수. 비율은 저장하지 않고 조회 시점에
    -- 건수 ÷ analyzed_chat으로 계산한다(API 1.6).
    analyzed_chat    INT NOT NULL DEFAULT 0,
    joy_count        INT NOT NULL DEFAULT 0,
    excitement_count INT NOT NULL DEFAULT 0,
    support_count    INT NOT NULL DEFAULT 0,
    surprise_count   INT NOT NULL DEFAULT 0,
    sadness_count    INT NOT NULL DEFAULT 0,
    anger_count      INT NOT NULL DEFAULT 0,
    confusion_count  INT NOT NULL DEFAULT 0,
    neutral_count    INT NOT NULL DEFAULT 0,

    -- LLM 분석 결과. 리포트 생성 전에는 NULL이다.
    narrative       TEXT,
    screen_context  TEXT,
    analyzed_at     TIMESTAMPTZ,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    analysis_status VARCHAR(20)  NOT NULL DEFAULT 'NOT_REQUESTED',
    analysis_error  VARCHAR(200),

    platform_session_id BIGINT
        REFERENCES broadcast_platform_sessions (id) ON DELETE SET NULL,

    -- API 1.4: 리포트 재생성 시 새 행을 만들지 않고 narrative를 갱신한다.
    -- (session_id, start_ms) 조회도 이 제약이 커버한다.
    CONSTRAINT uq_triggers_session_start UNIQUE (session_id, start_ms),

    CONSTRAINT ck_triggers_type      CHECK (trigger_type IN ('CHAT_SURGE')),
    CONSTRAINT ck_triggers_start_ms  CHECK (start_ms >= 0),
    CONSTRAINT ck_triggers_range     CHECK (end_ms > start_ms),
    CONSTRAINT ck_triggers_period    CHECK (ended_at > started_at),
    CONSTRAINT ck_triggers_counts    CHECK (
        chat_count >= 0 AND unique_chatters >= 0 AND avg_viewers >= 0
        AND analyzed_chat <= chat_count
    ),
    -- 8종 건수의 합은 항상 analyzed_chat과 같다. 조회 시점 나눗셈의 분모가
    -- 실제 분자 합과 어긋나면 비율의 합이 1이 아니게 된다.
    CONSTRAINT ck_triggers_sentiment_sum CHECK (
        analyzed_chat = joy_count + excitement_count + support_count + surprise_count
                      + sadness_count + anger_count + confusion_count + neutral_count
    ),
    CONSTRAINT ck_triggers_analysis_status
        CHECK (analysis_status IN ('NOT_REQUESTED', 'PENDING', 'COMPLETED', 'FAILED'))
);

CREATE INDEX ix_triggers_session_analysis_status
    ON triggers (session_id, analysis_status);

COMMENT ON TABLE  triggers                 IS '방송 중 확정된 하이라이트 트리거. 세션 리포트의 앵커다 (API 13.7)';
COMMENT ON COLUMN triggers.trigger_type    IS '현재 채팅 급증(CHAT_SURGE) 하나다. 시청자 급변 트리거는 판정 로직이 없다';
