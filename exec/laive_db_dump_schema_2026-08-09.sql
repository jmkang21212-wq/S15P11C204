-- promise_id의 FK는 promises 테이블 생성 후 이 파일 아래쪽에서 건다
-- (calendar_events → promises → broadcast_sessions → calendar_events 순환).
CREATE TABLE calendar_events (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id         BIGINT       NOT NULL REFERENCES streamers (id) ON DELETE CASCADE,
    platform_account_id BIGINT       REFERENCES platform_accounts (id) ON DELETE SET NULL,
    event_type          VARCHAR(20)  NOT NULL,
    title               VARCHAR(200) NOT NULL,
    memo                TEXT,
    start_at            TIMESTAMPTZ  NOT NULL,
    end_at              TIMESTAMPTZ  NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    promise_id          BIGINT,

    CONSTRAINT ck_calendar_events_event_type CHECK (event_type IN ('BROADCAST', 'DAY_OFF')),
    CONSTRAINT ck_calendar_events_status     CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    -- API 8.3: endAt은 startAt보다 늦어야 한다
    CONSTRAINT ck_calendar_events_period     CHECK (end_at > start_at),
    -- API 8.1: DAY_OFF만 platformAccountId = null을 허용한다
    CONSTRAINT ck_calendar_events_broadcast_platform
        CHECK (event_type <> 'BROADCAST' OR platform_account_id IS NOT NULL)
);

-- GET /calendar-events?from=&to= (최대 62일 범위 조회)
CREATE INDEX ix_calendar_events_streamer_start ON calendar_events (streamer_id, start_at);

-- GET /dashboard 의 upcomingBroadcast 조회
CREATE INDEX ix_calendar_events_upcoming
    ON calendar_events (streamer_id, start_at)
    WHERE status = 'SCHEDULED' AND event_type = 'BROADCAST';

-- 한 약속은 활성 일정을 둘 이상 가질 수 없다.
-- 취소된 일정(CANCELLED)을 제외해야 "취소 후 다른 날짜로 다시 잡기"가 가능하다.
-- 부분 UNIQUE 인덱스라 promise_id가 NULL인 직접 생성 일정끼리는 서로 충돌하지 않는다.
-- 이 인덱스는 약속 → 활성 일정 역참조(응답의 calendarEventId) 조회도 함께 태운다.
CREATE UNIQUE INDEX ux_calendar_events_promise
    ON calendar_events (promise_id)
    WHERE promise_id IS NOT NULL AND status <> 'CANCELLED';

CREATE TRIGGER trg_calendar_events_updated_at
    BEFORE UPDATE ON calendar_events
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE calendar_events IS '방송/휴방 일정 (SC-04)';
COMMENT ON COLUMN calendar_events.promise_id
    IS '전환의 출처가 된 약속. NULL이면 사용자가 직접 만든 일정';


-- 일정 하나가 여러 플랫폼으로 동시 송출될 수 있다. calendar_events의 단일
-- platform_account_id는 구버전 호환용으로 남아 있고, 트리거가 이 표와 동기화한다.
CREATE TABLE calendar_event_platform_accounts (
    calendar_event_id   BIGINT NOT NULL REFERENCES calendar_events (id) ON DELETE CASCADE,
    platform_account_id BIGINT NOT NULL REFERENCES platform_accounts (id) ON DELETE RESTRICT,

    CONSTRAINT pk_calendar_event_platform_accounts
        PRIMARY KEY (calendar_event_id, platform_account_id)
);


CREATE TABLE schedule_announcements (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_event_id BIGINT      NOT NULL REFERENCES calendar_events (id) ON DELETE CASCADE,
    content           TEXT        NOT NULL,
    ai_generated      BOOLEAN     NOT NULL DEFAULT false,
    publish_status    VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at      TIMESTAMPTZ,                     -- 초안·게시 실패 상태는 NULL (API 1.5)
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_schedule_announcements_publish_status
        CHECK (publish_status IN ('DRAFT', 'PUBLISHED', 'FAILED')),
    CONSTRAINT ck_schedule_announcements_published_at
        CHECK (publish_status <> 'PUBLISHED' OR published_at IS NOT NULL)
);

CREATE INDEX ix_schedule_announcements_calendar_event_id
    ON schedule_announcements (calendar_event_id);

CREATE TRIGGER trg_schedule_announcements_updated_at
    BEFORE UPDATE ON schedule_announcements
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE schedule_announcements IS '방송 일정 공지 초안·게시 (API 8.4)';


