-- -----------------------------------------------------------------------------
-- PLATFORM_ACCOUNTS : 플랫폼 연동 계정
--
-- access_token 등 토큰 컬럼은 platform_account_credentials로 옮겨졌으나,
-- 구버전 애플리케이션이 여전히 이 컬럼에 쓰기 때문에 남겨 둔다. 아래
-- trg_platform_accounts_sync_credential 트리거가 두 곳을 동기화한다.
-- 쓰기 경로가 완전히 정리되면 컬럼과 트리거를 함께 제거한다.
-- -----------------------------------------------------------------------------
CREATE TABLE platform_accounts (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id              BIGINT       NOT NULL REFERENCES streamers (id) ON DELETE CASCADE,
    platform                 VARCHAR(20)  NOT NULL,
    channel_id               VARCHAR(255) NOT NULL,
    channel_name             VARCHAR(100) NOT NULL,
    access_token             TEXT,
    refresh_token            TEXT,                     -- 플랫폼이 미제공할 수 있음 (API 1.5)
    connection_status        VARCHAR(20)  NOT NULL DEFAULT 'CONNECTED',
    connected_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    access_token_expires_at  TIMESTAMPTZ,
    refresh_token_expires_at TIMESTAMPTZ,
    scope                    TEXT,
    disconnected_at          TIMESTAMPTZ,
    last_synced_at           TIMESTAMPTZ,

    -- API 1.4: 동일 플랫폼 채널의 중복 연결 방지
    CONSTRAINT uq_platform_accounts_platform_channel UNIQUE (platform, channel_id),
    CONSTRAINT fk_platform_accounts_platform_catalog
        FOREIGN KEY (platform) REFERENCES streaming_platforms (code),
    CONSTRAINT ck_platform_accounts_connection_status
        CHECK (connection_status IN ('CONNECTED', 'DISCONNECTED', 'REAUTH_REQUIRED'))
);

CREATE INDEX ix_platform_accounts_streamer_id ON platform_accounts (streamer_id);

-- GET /portfolios?keyword= 의 채널명 부분 일치 검색
CREATE INDEX ix_platform_accounts_channel_name_trgm
    ON platform_accounts USING gin (channel_name gin_trgm_ops);

CREATE TRIGGER trg_platform_accounts_updated_at
    BEFORE UPDATE ON platform_accounts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE  platform_accounts               IS '방송 플랫폼(치지직/SOOP) OAuth 연동 계정';
COMMENT ON COLUMN platform_accounts.access_token  IS 'NFR-S-03: 애플리케이션에서 암호화한 값을 저장한다. 평문 저장 금지';
COMMENT ON COLUMN platform_accounts.refresh_token IS 'NFR-S-03: 애플리케이션에서 암호화한 값을 저장한다. 평문 저장 금지';
COMMENT ON COLUMN platform_accounts.access_token_expires_at
    IS '플랫폼 Access Token 만료 시각. 이 시각 직전에 Refresh Token으로 갱신한다';
COMMENT ON COLUMN platform_accounts.refresh_token_expires_at
    IS '플랫폼 Refresh Token 만료 시각. 지나면 재연동(REAUTH_REQUIRED)만 가능하다';
COMMENT ON COLUMN platform_accounts.scope
    IS '플랫폼이 부여한 scope 원문. 공백 구분 표시명이므로 파싱하지 않는다';


-- -----------------------------------------------------------------------------
-- PLATFORM_ACCOUNT_CREDENTIALS : 플랫폼 자격 증명
--
-- 플랫폼마다 인증 방식이 달라(OAuth2 / API Key / 자체 스킴) 토큰 컬럼을 고정으로
-- 두면 플랫폼을 늘릴 때마다 컬럼이 늘어난다. 암호화된 페이로드 하나로 받는다.
-- -----------------------------------------------------------------------------
CREATE TABLE platform_account_credentials (
    platform_account_id          BIGINT      PRIMARY KEY
        REFERENCES platform_accounts (id) ON DELETE CASCADE,
    auth_scheme                  VARCHAR(20) NOT NULL,
    encrypted_credential_payload TEXT        NOT NULL,
    encryption_key_version       VARCHAR(20) NOT NULL DEFAULT 'v1',
    access_expires_at            TIMESTAMPTZ,
    refresh_expires_at           TIMESTAMPTZ,
    scopes                       TEXT,
    credential_version           BIGINT      NOT NULL DEFAULT 1,
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_platform_credentials_auth_scheme
        CHECK (auth_scheme IN ('OAUTH2', 'API_KEY', 'CUSTOM')),
    CONSTRAINT ck_platform_credentials_version CHECK (credential_version > 0)
);

CREATE TRIGGER trg_platform_account_credentials_updated_at
    BEFORE UPDATE ON platform_account_credentials
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


