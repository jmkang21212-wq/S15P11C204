    provider_user_id VARCHAR(255) NOT NULL,
    provider_email   VARCHAR(255),                     -- 제공자가 이메일 미제공 시 NULL (API 1.5)
    connected_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

