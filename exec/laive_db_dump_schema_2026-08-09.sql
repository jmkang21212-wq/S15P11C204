-- -----------------------------------------------------------------------------
-- BROADCAST_SESSIONS : 논리 방송 세션
--
-- platform_account_id는 다중 플랫폼 도입 전의 단일 대표 계정이다.
-- 실제 플랫폼별 상태는 broadcast_platform_sessions가 갖는다. 아래
-- trg_broadcast_sessions_ensure_platform_child 트리거가 대표 자식 행을 만든다.
-- -----------------------------------------------------------------------------
CREATE TABLE broadcast_sessions (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id         BIGINT       NOT NULL REFERENCES streamers (id)         ON DELETE CASCADE,
    platform_account_id BIGINT       NOT NULL REFERENCES platform_accounts (id) ON DELETE RESTRICT,
    calendar_event_id   BIGINT       REFERENCES calendar_events (id) ON DELETE SET NULL,
    title               VARCHAR(200) NOT NULL,
