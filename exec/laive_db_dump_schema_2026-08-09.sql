-- =============================================================================
-- LAIVE - 1인 스트리머 AI 매니저
-- V1: 베이스라인 스키마 (PostgreSQL 18 / TimescaleDB 2.28)
--
-- 이 파일은 이전 V1~V21 마이그레이션 21개를 하나로 접은 결과다. 스키마의 최종
-- 상태만 담으며, 중간 과정(추가 후 삭제된 테이블·컬럼, expand/contract 단계)은
-- 남기지 않는다. 삭제된 것들: report_segments, sentiment_snapshots,
-- repeated_questions 초안 스키마, reports의 3분류 비율 컬럼.
--
-- 설계 원칙
--   - 모든 PK/FK는 bigint (API 명세서 1.3)
--   - 모든 시각 컬럼은 timestamptz (UTC 저장, API는 ISO 8601 UTC로 직렬화)
--   - ERD의 enum은 varchar + CHECK 제약으로 구현한다.
--     이 프로젝트는 JPA가 아닌 MyBatis를 사용하므로 네이티브 ENUM 타입은
--     매퍼마다 ::text 캐스팅이 필요하고, 값 추가 시 ALTER TYPE이 필요하다.
--     varchar + CHECK는 마이그레이션으로 값 집합을 변경할 수 있고
--     map-underscore-to-camel-case 기반 매핑과도 그대로 호환된다.
--   - TimescaleDB hypertable 전환은 이 파일 마지막 절에서 수행한다.
--     hypertable 대상 테이블의 PK/UNIQUE에는 파티션 컬럼이 반드시 포함되어야
--     하므로, 테이블 정의 시점에 미리 복합 키로 잡아 둔다.
--
-- 테이블 생성 순서는 FK 의존성을 따른다. 순환 참조 두 곳
-- (calendar_events ↔ promises, growth_roadmaps ↔ growth_roadmap_generations)은
-- 각 절 끝의 ALTER TABLE로 닫는다.
--
-- 트랜잭션에 대하여
--   이 파일은 Flyway 기본값대로 하나의 트랜잭션에서 실행되며, 실패하면 아무것도
--   남기지 않는다. TimescaleDB 2.28 기준으로 연속 집계 생성과 컬럼스토어 정책
--   CALL이 트랜잭션 블록 안에서 정상 동작하는 것을 확인했다. 구버전(대략 2.10
--   이전)은 이 둘을 트랜잭션 밖에서만 허용하므로, 그런 환경에 올릴 때는 마지막
--   절을 별도 파일로 떼고 동봉 .conf에 executeInTransaction=false를 준다.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS timescaledb;
-- 포트폴리오 검색(GET /portfolios?keyword=)의 채널명·태그명 부분 일치 검색용
CREATE EXTENSION IF NOT EXISTS pg_trgm;


-- -----------------------------------------------------------------------------
-- 공통: updated_at 자동 갱신
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;


