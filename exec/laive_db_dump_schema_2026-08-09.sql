    CONSTRAINT uq_social_accounts_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT ck_social_accounts_provider CHECK (provider IN ('GOOGLE', 'NAVER', 'KAKAO'))
);

CREATE INDEX ix_social_accounts_streamer_id ON social_accounts (streamer_id);

COMMENT ON TABLE social_accounts IS '소셜 로그인 계정 연동 정보 (API 6.3)';


