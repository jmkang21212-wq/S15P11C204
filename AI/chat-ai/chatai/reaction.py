"""
리액션(순수 반응) 판별 — 여러 기능이 공유한다.

"내용 없이 반응만 있는 채팅"을 걸러낸다. 두 곳에서 쓰이는데 목적이 다르다:

  /summary  : 챈트를 LLM에 안 보낸다. 그 정보는 distribution 수치가 이미
              전달하므로 텍스트로 또 보내면 같은 정보의 이중 지불이다.
  /questions: 반복 질문을 빈도로만 세면 상위가 전부 리액션이 된다.
              실측(VOD 238,199건)에서 물음표 채팅 상위가
              `???` 318회 · `ㅇㄴ?` 191회 · `난가?` 69회로, 진짜 질문이
              하나도 못 올라왔다.

판별은 LLM 없이 문자 구성만 본다 — 리액션 문자를 제거하고 남는 게 2자 미만이면
리액션. 실측 상위 챈트를 전부 커버한다.
"""

# 리액션 문자: 이것만으로 이뤄진 채팅은 "내용 없는 순수 반응"으로 본다.
# 한글 자모(ㄱ-ㅣ, U+3131~U+3163) + 감탄 부호. 제거 후 2자 미만 남으면 리액션.
_REACT_CHARS = set(chr(c) for c in range(0x3131, 0x3164)) | set('!?~.…,;^ㆍ-_ ')


def is_reaction(text):
    """ㅋㅋㅋ·캬ㅑㅑ·네ㅔㅔ·ㄷㄷ → True / 개웃기네·왜 화면 멈춰요 → False"""
    content = [ch for ch in text if ch not in _REACT_CHARS]
    return len(content) < 2
