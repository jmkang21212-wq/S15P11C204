-- =============================================================================
-- V4: 보관 기간(Retention) 정책
--
-- ⚠ 이 파일의 정책은 오래된 청크를 "복구 불가하게 삭제"한다.
--   API 명세서 16장의 체크리스트 "음성, 채팅, STT 전문의 보관 기간"이
--   확정되면 값을 조정하고, 필요 없는 정책은 remove_retention_policy로 제거한다.
--
--   정책 확인 : SELECT * FROM timescaledb_information.jobs
--                WHERE proc_name = 'policy_retention';
--   정책 제거 : SELECT remove_retention_policy('chat_messages');
-- =============================================================================


-- -----------------------------------------------------------------------------
-- chat_messages : 90일
--
-- 프로젝트 명세서 10.2 "세션당 수만~수십만 건이 쌓이므로 보관 기간(예: 90일)
-- 정책을 적용한다" 에 따른다.
--
-- 영향: 90일이 지난 세션은 GET /highlights/{id}/chat-replay 가 빈 목록을 반환한다.
--       리포트의 total_chat·채팅 피크는 reports / chat_message_counts_1m 에
--       이미 집계되어 있으므로 영향을 받지 않는다.
-- -----------------------------------------------------------------------------
SELECT add_retention_policy('chat_messages', INTERVAL '90 days', if_not_exists => true);


-- -----------------------------------------------------------------------------
-- live_briefings : 90일
--
-- 브리핑 피드는 방송 중 실시간 콘솔에서만 사용하고,
-- 방송 후에는 세션 리포트가 대체한다.
-- -----------------------------------------------------------------------------
SELECT add_retention_policy('live_briefings', INTERVAL '90 days', if_not_exists => true);


-- -----------------------------------------------------------------------------
-- sentiment_snapshots : 90일
--
-- 이 테이블은 chat_messages를 3분 윈도우로 요약한 파생 데이터다(API 13.6).
-- 원본 채팅이 90일에 사라지면 값을 재계산하거나 검증할 방법도 없으므로
-- 원본보다 오래 보관할 이유가 없다. chat_messages·live_briefings와 맞춘다.
--
-- 세션 종료 후 이 테이블을 읽는 API는 없다. 세션 단위 감정 비율은
-- REPORTS.positive_ratio 등에 영구 보존되고,
-- live-snapshot은 방송 중 최신 1건만 조회한다.
-- 방송 후에 남기는 이유는 리포트 재생성·디버깅 여유분이다.
-- -----------------------------------------------------------------------------
SELECT add_retention_policy('sentiment_snapshots', INTERVAL '90 days', if_not_exists => true);


-- -----------------------------------------------------------------------------
-- viewer_metrics : 보관 정책 없음 (영구 보존)
--
-- 프로젝트 명세서 10.2가 보관 기간 대상으로 언급하지만, 실측 결과 적용할
-- 이유가 없다. 압축 후 세션당 1.8kB, 행당 10바이트다.
-- (스트리머 50명 × 주 4회 × 3시간 × 1년 = 187만 행 → 18MB, 압축비 16.3배)
-- 1,000명 규모로 10년을 모아도 4GB 미만이다.
--
-- 반면 세션 리포트(SC-06)의 viewerTimeline이 이 원본을 직접 조회하므로
-- 삭제하면 과거 방송의 시청자 추이 그래프가 빈 배열이 된다.
-- 성장 추이를 다루는 서비스에서 그 손실이 절약분보다 크다.
-- -----------------------------------------------------------------------------


