-- =============================================================================
-- LAIVE - 1인 스트리머 AI 매니저
-- V9: 수집 공백 구간
--
-- 명세 16장 "수집 공백 가드" 항목이 지목한 저장 위치를 만든다. 트리거 판정이
-- 입력으로 쓸 자리가 현재 스키마에 없어서 가드를 구현할 수 없었다.
--
-- 왜 필요한가
--   치지직 socket.io는 세션 인증 URL의 쿼리스트링 인증값이 재사용되지 않아
--   자동 재연결이 불가능하다. 끊기면 auth → connect → SYSTEM sessionKey →
--   subscribe 전체를 다시 밟아야 하고, 그동안의 채팅은 재생되지 않아 영구
--   유실된다. 유실 자체는 막을 수 없으므로 "이 구간은 못 봤다"를 남긴다.
--
--   기록하지 않으면 두 가지가 조용히 틀어진다.
--     1) 리포트가 공백 구간을 "조용한 방송"으로 오집계한다.
--     2) 더 심각한 쪽 — 공백 동안 uniq가 0으로 떨어져 15분 baseline에
--        인위적으로 낮은 값이 채워지고, 복구 직후의 정상 채팅이 급증으로
--        오탐된다. HIGHLIGHT_SPEC의 median·MAD가 극단값에 강건하다는 전제는
--        공백이 없다는 가정에 기대고 있다.
--   트리거 판정은 이 구간에 걸친 틱을 판정에서 제외하고 baseline에도 넣지
--   않는다.
--
-- hypertable로 만들지 않는 이유
--   세션당 0~수 행이다. triggers와 같은 판단이다(V8).
--
-- 보관 정책을 걸지 않는 이유
--   공백은 원본이 아니라 "원본이 없다는 사실"이다. chat_messages가 90일에
--   삭제된 뒤 남아야 할 메타데이터이며, 이걸 함께 지우면 과거 리포트의
--   채팅량이 왜 낮았는지 설명할 근거가 사라진다.
-- =============================================================================

CREATE TABLE collection_gaps (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT      NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,

    -- 끊김을 감지한 시각. 마지막으로 정상 수신한 시각이 아니라 수집기가
    -- 연결 상실을 인지한 시각이다. 둘 사이의 차이는 socket.io ping 간격만큼이며
    -- 그 구간도 수신이 없었으므로 공백에 포함하는 쪽이 안전하다.
    started_at TIMESTAMPTZ NOT NULL,

    -- 재핸드셰이크로 구독을 회복한 시각. 복구 전에는 NULL이다.
    --
    -- 처음부터 닫힌 구간으로 받지 않는 이유: 수집기가 공백 도중에 죽으면
    -- 그 공백은 영원히 보고되지 않는다. 열어 두고 나중에 닫으면 수집기가
    -- 죽어도 "여기서부터 못 봤다"는 사실은 남는다. 세션 종료 시 Spring이
    -- 남은 열린 구간을 종료 시각으로 닫는다.
    ended_at   TIMESTAMPTZ,

    reason     VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- 수집기의 공백 보고는 재시도된다. 같은 시작 시각의 보고는 새 행을
    -- 만들지 않고 ended_at만 갱신한다.
    CONSTRAINT uq_collection_gaps_session_started UNIQUE (session_id, started_at),

    CONSTRAINT ck_collection_gaps_period CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_collection_gaps_reason CHECK (reason IN (
        -- socket.io 연결이 끊겼다. 가장 흔한 경우다.
        'DISCONNECTED',
        -- 같은 인증 URL로 재연결을 시도해 서버가 auth fail로 끊었다.
        'AUTH_FAILED',
        -- 핸드셰이크는 됐으나 chat 구독 요청이 실패했다.
        'SUBSCRIBE_FAILED',
        -- 수집기 프로세스가 내려갔다. 하트비트 만료로 Spring이 기록한다.
        'COLLECTOR_STOPPED'
    ))
);

-- 트리거 판정과 리포트 모두 "이 세션의 공백을 시간순으로" 읽는다.
-- uq_collection_gaps_session_started가 (session_id, started_at) 선두라
-- 그대로 커버하므로 별도 인덱스를 만들지 않는다.

COMMENT ON TABLE  collection_gaps            IS '채팅 수집이 끊긴 구간. 트리거 판정에서 제외하고 리포트가 오집계하지 않게 한다';
COMMENT ON COLUMN collection_gaps.ended_at   IS '구독 회복 시각. 복구 전에는 NULL이며 세션 종료 시 종료 시각으로 닫힌다';
COMMENT ON COLUMN collection_gaps.reason     IS 'DISCONNECTED / AUTH_FAILED / SUBSCRIBE_FAILED / COLLECTOR_STOPPED';
