ALTER TABLE growth_goals
    ADD COLUMN revision BIGINT NOT NULL DEFAULT 1,
    ADD CONSTRAINT ck_growth_goals_revision CHECK (revision > 0);

CREATE TABLE growth_action_generations (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    growth_goal_id    BIGINT       NOT NULL REFERENCES growth_goals (id) ON DELETE CASCADE,
    source_report_id  BIGINT       REFERENCES reports (id) ON DELETE SET NULL,
    goal_revision     BIGINT       NOT NULL,
    trigger_type      VARCHAR(30)  NOT NULL,
    status            VARCHAR(30)  NOT NULL,
    prompt_version    VARCHAR(100) NOT NULL,
    idempotency_key   VARCHAR(200) NOT NULL,
    input_fingerprint VARCHAR(64),
    requested_at      TIMESTAMPTZ  NOT NULL,
    started_at        TIMESTAMPTZ,
    completed_at      TIMESTAMPTZ,
    error_code        VARCHAR(100),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_growth_action_generations_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_growth_action_generations_revision CHECK (goal_revision > 0),
    CONSTRAINT ck_growth_action_generations_trigger CHECK (
        trigger_type IN ('GOAL_CREATED', 'GOAL_UPDATED', 'REPORT_COMPLETED', 'MANUAL')
    ),
    CONSTRAINT ck_growth_action_generations_status CHECK (
        status IN ('WAITING_FOR_DATA', 'PENDING', 'PROCESSING',
                   'COMPLETED', 'FAILED', 'SUPERSEDED')
    )
);

CREATE INDEX ix_growth_action_generations_goal_requested
    ON growth_action_generations (growth_goal_id, requested_at DESC, id DESC);

CREATE INDEX ix_growth_action_generations_pending
    ON growth_action_generations (status, requested_at)
    WHERE status = 'PENDING';

CREATE TRIGGER trg_growth_action_generations_updated_at
    BEFORE UPDATE ON growth_action_generations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE growth_actions
    ADD COLUMN generation_id BIGINT
        REFERENCES growth_action_generations (id) ON DELETE SET NULL;

CREATE INDEX ix_growth_actions_generation_id
    ON growth_actions (generation_id);

-- The outbox is now shared by broadcast-session and growth aggregates.
ALTER TABLE broadcast_session_outbox
    DROP CONSTRAINT broadcast_session_outbox_aggregate_id_fkey;

ALTER TABLE broadcast_session_outbox
    DROP CONSTRAINT ck_broadcast_session_outbox_event_type;

ALTER TABLE broadcast_session_outbox
    ADD CONSTRAINT ck_broadcast_session_outbox_event_type CHECK (
        event_type IN (
            'PREPARATION_REQUESTED',
            'BROADCAST_STARTED',
            'BROADCAST_ENDED',
            'TRIGGER_ANALYSIS_REQUESTED',
            'REPORT_FINALIZATION_REQUESTED',
            'GROWTH_ACTION_GENERATION_REQUESTED'
        )
    );

COMMENT ON TABLE growth_action_generations
    IS 'Growth action generation history, idempotency and public generation state.';
COMMENT ON COLUMN broadcast_session_outbox.aggregate_id
    IS 'Polymorphic aggregate id. Session id for broadcast events and growth goal id for growth events.';
