-- =============================================================================
-- LAIVE - 1인 스트리머 AI 매니저
-- V8: 트리거 앵커 리포트 구조
--
-- API 명세 1.6 / 11.1 / 13.6 / 13.7 개정을 DDL에 반영한다. 축은 두 가지다.
--
--   1) 채팅 감정을 3분류 비율이 아니라 8종 라벨 건별로 저장한다.
--      채팅 AI가 건별 라벨을 돌려주므로(AI/CHAT_AI_API.md의 /ingest 응답
--      results) 원본 옆에 그대로 남기면 어떤 구간의 분포든 조회 시점에
--      집계된다. 3분류로 눌러 저장하면 `놀람`·`혼란/질문`을 어디에 넣을지가
--      자의적이고, 기준을 바꿨을 때 과거 리포트와 추이를 비교할 수 없다.
--      윈도우 요약 테이블(sentiment_snapshots)과 그 가중치(V7)가 함께 불필요해진다.
--
--   2) 리포트의 기준점을 방송 중 확정되는 트리거로 옮긴다.
--      report_segments는 report_id를 필수로 요구하는데 reports 행은 방송
--      종료 시 생성되므로 방송 중에 앵커를 저장할 수 없었다.
--
-- 이 마이그레이션은 테이블 두 개를 삭제한다. 작성 시점에 두 테이블은
-- 참조하는 애플리케이션 코드가 없고 행도 없다.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1) chat_messages : 건별 감정 라벨
--
-- 분류 호출이 실패하면 그 배치는 재시도하지 않고 건너뛰며 원본만 저장한다
-- (AI/CHAT_AI_API.md). AI 장애가 채팅 수집을 멈추게 하면 안 되고, 라벨은
-- 저장된 원본으로 재분류할 수 있지만 원본 유실은 복구할 수 없다.
-- 따라서 이 컬럼은 NULL을 허용해야 한다.
-- -----------------------------------------------------------------------------
ALTER TABLE chat_messages
    ADD COLUMN sentiment_label VARCHAR(20)
        CONSTRAINT ck_chat_messages_sentiment_label
        CHECK (sentiment_label IN ('JOY', 'EXCITEMENT', 'SUPPORT', 'SURPRISE',
                                   'SADNESS', 'ANGER', 'CONFUSION', 'NEUTRAL'));

COMMENT ON COLUMN chat_messages.sentiment_label
    IS '채팅 AI 8종 라벨의 ASCII 코드(API 13.6 라벨 코드 표). 분류 실패 시 NULL';

-- 라벨 전용 인덱스는 만들지 않는다.
-- 세션 분포 집계는 ix_chat_messages_session_sent (session_id, sent_at, id)로
-- 세션 범위를 좁힌 뒤 힙에서 라벨을 읽는다. 라벨을 인덱스에 포함시키면
-- 최대 볼륨 테이블의 인덱스가 청크마다 복제되므로(V1 viewer_metrics 주석과
-- 같은 이유) 비용이 곱해진다. 필요해지면 그때 INCLUDE로 덧붙인다.


-- -----------------------------------------------------------------------------
-- 2) triggers : 리포트 앵커
--
-- 판정 알고리즘은 AI/chat-ai/HIGHLIGHT_SPEC.md이며 Spring이 자체 수행한다.
-- 구간이 확정될 때마다 한 행을 append한다.
--
-- 보관 정책을 걸지 않는 이유
--   트리거는 원본이 아니라 구간 요약이고, chat_messages가 90일에 삭제된 뒤
--   남겨야 할 것이 바로 그 요약이다. viewer_metrics에 적용한 것과 같은
--   판단이다(V4). 세션당 수~수십 행이라 절약분도 없다.
--
-- hypertable로 만들지 않는 이유
--   세션당 수~수십 행이라 파티셔닝 이득이 없다. risk_events와 같은 판단이며,
--   highlights가 이 테이블에 FK를 걸어야 하므로 hypertable이면 안 된다.
-- -----------------------------------------------------------------------------
CREATE TABLE triggers (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT       NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    trigger_type    VARCHAR(30)  NOT NULL,
    transcript_id   BIGINT       REFERENCES transcripts (id) ON DELETE SET NULL,

    -- 시각은 오프셋과 절대 시각을 둘 다 저장한다. transcripts는 오프셋으로,
    -- chat_messages는 절대 시각으로 조회하므로 소비자마다 필요한 형태가 다르다.
    -- 확정 시점의 Spring은 둘 다 알고 있고, 조회할 때마다 세션 시작 시각과
    -- 조인해 변환하면 오프셋과 절대 시각을 섞는 실수가 조인 지점마다 되살아난다.
    start_ms        BIGINT       NOT NULL,
    end_ms          BIGINT       NOT NULL,
    started_at      TIMESTAMPTZ  NOT NULL,
    ended_at        TIMESTAMPTZ  NOT NULL,

    -- 판정 지표. 상태기계가 구간을 확정했다는 것은 이 값들이 모두 계산됐다는
    -- 뜻이므로 NOT NULL이다. peak_z는 MAD 하한 ε=0.001에서 최대 약 675까지
    -- 나올 수 있어 정수부를 3자리 확보한다.
    peak_z          NUMERIC(6,3) NOT NULL,
    peak_engagement NUMERIC(5,4) NOT NULL,
    avg_viewers     INT          NOT NULL,
    chat_count      INT          NOT NULL,
    unique_chatters INT          NOT NULL,

    -- 구간 채팅의 라벨별 건수. 비율은 저장하지 않고 조회 시점에
    -- 건수 ÷ analyzed_chat으로 계산한다(API 1.6).
    analyzed_chat    INT NOT NULL DEFAULT 0,
    joy_count        INT NOT NULL DEFAULT 0,
    excitement_count INT NOT NULL DEFAULT 0,
    support_count    INT NOT NULL DEFAULT 0,
    surprise_count   INT NOT NULL DEFAULT 0,
    sadness_count    INT NOT NULL DEFAULT 0,
    anger_count      INT NOT NULL DEFAULT 0,
    confusion_count  INT NOT NULL DEFAULT 0,
    neutral_count    INT NOT NULL DEFAULT 0,

    -- LLM 분석 결과. 리포트 생성 전에는 NULL이다.
    narrative       TEXT,
    screen_context  TEXT,
    analyzed_at     TIMESTAMPTZ,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- API 1.4: 리포트 재생성 시 새 행을 만들지 않고 narrative를 갱신한다.
    CONSTRAINT uq_triggers_session_start UNIQUE (session_id, start_ms),

    CONSTRAINT ck_triggers_type      CHECK (trigger_type IN ('CHAT_SURGE')),
    CONSTRAINT ck_triggers_start_ms  CHECK (start_ms >= 0),
    CONSTRAINT ck_triggers_range     CHECK (end_ms > start_ms),
    CONSTRAINT ck_triggers_period    CHECK (ended_at > started_at),
    CONSTRAINT ck_triggers_counts    CHECK (
        chat_count >= 0 AND unique_chatters >= 0 AND avg_viewers >= 0
        AND analyzed_chat <= chat_count
    ),
    -- 8종 건수의 합은 항상 analyzed_chat과 같다. 조회 시점 나눗셈의 분모가
    -- 실제 분자 합과 어긋나면 비율의 합이 1이 아니게 된다.
    CONSTRAINT ck_triggers_sentiment_sum CHECK (
        analyzed_chat = joy_count + excitement_count + support_count + surprise_count
                      + sadness_count + anger_count + confusion_count + neutral_count
    )
);

-- (session_id, start_ms) 조회는 uq_triggers_session_start가 커버하므로
-- 별도 인덱스를 만들지 않는다.

COMMENT ON TABLE  triggers                IS '방송 중 확정된 하이라이트 트리거. 세션 리포트의 앵커다 (API 13.7)';
COMMENT ON COLUMN triggers.trigger_type   IS '현재 채팅 급증(CHAT_SURGE) 하나다. 시청자 급변 트리거는 판정 로직이 없다';
COMMENT ON COLUMN triggers.narrative      IS '급증 원인 설명. LLM이 채운다. 리포트 생성 전·분석 실패 시 NULL';
COMMENT ON COLUMN triggers.screen_context IS '화면 맥락. 캡처 기능 도입 전까지 전 구간 NULL';


-- -----------------------------------------------------------------------------
-- 3) highlights : 앵커 참조를 트리거로 옮긴다
--
-- report_segments의 HIGHLIGHT 종류와 이 테이블은 의미가 겹쳤다. 역할을
-- 나눠서 triggers는 "리포트가 설명하는 구간", highlights는 "클립을 만든
-- 구간"으로 둔다. 모든 트리거가 클립이 되지는 않으므로 분리를 유지한다.
-- -----------------------------------------------------------------------------
ALTER TABLE highlights
    DROP CONSTRAINT highlights_report_segment_id_fkey;

ALTER TABLE highlights
    RENAME COLUMN report_segment_id TO trigger_id;

ALTER TABLE highlights
    ADD CONSTRAINT highlights_trigger_id_fkey
        FOREIGN KEY (trigger_id) REFERENCES triggers (id) ON DELETE SET NULL;

ALTER INDEX ix_highlights_report_segment_id RENAME TO ix_highlights_trigger_id;


-- -----------------------------------------------------------------------------
-- 4) report_segments 폐기
-- -----------------------------------------------------------------------------
DROP TABLE report_segments;


-- -----------------------------------------------------------------------------
-- 5) sentiment_snapshots 폐기
--
-- 남는 역할이 방송 중 현재값 하나였는데, 그 값은 채팅 AI가 /ingest 응답의
-- window로 매초 주는 것을 그대로 프론트에 중계하고 재연결 복구용으로만
-- Redis에 최신 1건을 남긴다(API 1.6, 10.6). 건별 라벨이 chat_messages에
-- 있으므로 윈도우 요약본을 DB에 보관할 이유가 없다.
--
-- V7이 추가한 message_count도 이 테이블과 함께 사라진다. 가중 평균은 건별
-- 집계로 대체되어 가중치 컬럼 자체가 필요 없다.
--
-- DROP TABLE은 hypertable에 붙은 컬럼스토어 정책(V2)과 보존 정책(V4)의
-- 백그라운드 job도 함께 정리한다.
-- -----------------------------------------------------------------------------
DROP TABLE sentiment_snapshots;


-- -----------------------------------------------------------------------------
-- 6) reports : 3분류 비율 → 8종 건수
--
-- 비율이 아니라 건수를 저장하는 이유
--   - 비율 8개를 NUMERIC(4,3)으로 저장하면 반올림 때문에 합이 1에서
--     최대 ±0.004까지 벌어진다. 건수는 나눗셈이 조회 시점에 일어나므로
--     합이 항상 정확히 1이다.
--   - 성장 리포트가 여러 세션을 묶을 때 SUM(joy_count)/SUM(analyzed_chat)이
--     되어 채팅량 가중이 자동으로 걸린다. 세션별 비율을 평균하면 조용한
--     방송과 대박 방송이 같은 비중이 된다.
--   - analyzed_chat / total_chat이 곧 분류 커버리지이며 PARTIAL 판정 근거다.
--
-- 집계가 완료되지 않은 PROCESSING 상태에서는 NULL이다(API 1.5).
-- -----------------------------------------------------------------------------
ALTER TABLE reports
    DROP COLUMN positive_ratio,
    DROP COLUMN neutral_ratio,
    DROP COLUMN negative_ratio,
    ADD COLUMN analyzed_chat    BIGINT,
    ADD COLUMN joy_count        BIGINT,
    ADD COLUMN excitement_count BIGINT,
    ADD COLUMN support_count    BIGINT,
    ADD COLUMN surprise_count   BIGINT,
    ADD COLUMN sadness_count    BIGINT,
    ADD COLUMN anger_count      BIGINT,
    ADD COLUMN confusion_count  BIGINT,
    ADD COLUMN neutral_count    BIGINT;

-- 아홉 컬럼은 전부 채워지거나 전부 NULL이어야 한다. 일부만 채워지면
-- 합 검증이 NULL로 통과해버려 분모와 분자가 어긋난 채 저장된다.
ALTER TABLE reports
    ADD CONSTRAINT ck_reports_sentiment_presence CHECK (
        num_nulls(analyzed_chat, joy_count, excitement_count, support_count,
                  surprise_count, sadness_count, anger_count, confusion_count,
                  neutral_count) IN (0, 9)
    ),
    ADD CONSTRAINT ck_reports_sentiment_sum CHECK (
        analyzed_chat IS NULL OR
        analyzed_chat = joy_count + excitement_count + support_count + surprise_count
                      + sadness_count + anger_count + confusion_count + neutral_count
    ),
    ADD CONSTRAINT ck_reports_analyzed_chat CHECK (
        analyzed_chat IS NULL OR total_chat IS NULL OR analyzed_chat <= total_chat
    );

COMMENT ON COLUMN reports.analyzed_chat
    IS 'sentiment_label이 붙은 채팅 수. total_chat과의 비가 분류 커버리지다';


-- -----------------------------------------------------------------------------
-- 7) Outbox : 리포트 생성 작업 이벤트
--
-- 세션 리포트는 Spring 내부에서 생성하며(API 13.7) 이미 있는 Outbox를
-- 잡 큐로 재사용한다. 트리거 하나당 이벤트 하나를 발행하는 이유:
--   - 한 이벤트에서 트리거 전부를 순차 처리하면 LLM 지연이 쌓여 선점 임대
--     시간(locked_until)을 넘기고 다른 워커가 같은 작업을 중복 선점한다.
--   - 트리거 하나가 실패했을 때 그것만 재시도할 수 있다.
--
-- aggregate_id는 그대로 session_id를 쓰고 trigger_id는 payload에 담는다.
-- 멱등 키는 deduplication_key로 구분한다.
-- -----------------------------------------------------------------------------
ALTER TABLE broadcast_session_outbox
    DROP CONSTRAINT ck_broadcast_session_outbox_event_type;

ALTER TABLE broadcast_session_outbox
    ADD CONSTRAINT ck_broadcast_session_outbox_event_type
        CHECK (event_type IN (
            'PREPARATION_REQUESTED',
            'BROADCAST_STARTED',
            'BROADCAST_ENDED',
            'TRIGGER_ANALYSIS_REQUESTED',
            'REPORT_FINALIZATION_REQUESTED'
        ));
