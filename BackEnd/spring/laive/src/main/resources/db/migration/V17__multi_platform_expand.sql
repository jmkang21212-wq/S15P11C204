    platform_session_id BIGINT      NOT NULL
        REFERENCES broadcast_platform_sessions (id) ON DELETE CASCADE,
    capability_code     VARCHAR(40) NOT NULL,
    support_status      VARCHAR(20) NOT NULL,
    run_status          VARCHAR(20) NOT NULL,
    last_succeeded_at   TIMESTAMPTZ,
    error_code          VARCHAR(100),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_platform_session_capability_runs
