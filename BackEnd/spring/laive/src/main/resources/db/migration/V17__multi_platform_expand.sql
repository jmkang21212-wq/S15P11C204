INSERT INTO platform_account_credentials (
    platform_account_id, auth_scheme, encrypted_credential_payload,
    access_expires_at, refresh_expires_at, scopes
)
SELECT id,
       'OAUTH2',
       jsonb_build_object('accessToken', access_token, 'refreshToken', refresh_token)::text,
       access_token_expires_at,
       refresh_token_expires_at,
       scope
  FROM platform_accounts
 WHERE access_token IS NOT NULL;

-- Expand-period dual write: old application versions still write token columns on
-- platform_accounts while the new credential table remains the migration target.
CREATE OR REPLACE FUNCTION sync_platform_account_credential()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.access_token IS NULL THEN
        DELETE FROM platform_account_credentials WHERE platform_account_id = NEW.id;
        RETURN NEW;
    END IF;

    INSERT INTO platform_account_credentials (
        platform_account_id, auth_scheme, encrypted_credential_payload,
        access_expires_at, refresh_expires_at, scopes
    ) VALUES (
        NEW.id,
        'OAUTH2',
        jsonb_build_object('accessToken', NEW.access_token, 'refreshToken', NEW.refresh_token)::text,
        NEW.access_token_expires_at,
        NEW.refresh_token_expires_at,
        NEW.scope
    )
    ON CONFLICT (platform_account_id) DO UPDATE
       SET encrypted_credential_payload = EXCLUDED.encrypted_credential_payload,
           access_expires_at = EXCLUDED.access_expires_at,
           refresh_expires_at = EXCLUDED.refresh_expires_at,
           scopes = EXCLUDED.scopes,
           credential_version = platform_account_credentials.credential_version + 1;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_platform_accounts_sync_credential
    AFTER INSERT OR UPDATE OF access_token, refresh_token, access_token_expires_at,
                              refresh_token_expires_at, scope
    ON platform_accounts
    FOR EACH ROW EXECUTE FUNCTION sync_platform_account_credential();

CREATE TABLE broadcast_platform_sessions (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_session_id BIGINT       NOT NULL
        REFERENCES broadcast_sessions (id) ON DELETE CASCADE,
    platform_account_id  BIGINT       NOT NULL
        REFERENCES platform_accounts (id) ON DELETE RESTRICT,
    status               VARCHAR(20)  NOT NULL DEFAULT 'PREPARING',
    started_at           TIMESTAMPTZ,
    ended_at             TIMESTAMPTZ,
    last_synced_at       TIMESTAMPTZ,
    error_code           VARCHAR(100),
    provider_metadata    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_broadcast_platform_sessions_account
        UNIQUE (broadcast_session_id, platform_account_id),
    CONSTRAINT ck_broadcast_platform_sessions_status
        CHECK (status IN ('PREPARING', 'LIVE', 'ENDED', 'FAILED')),
    CONSTRAINT ck_broadcast_platform_sessions_period
        CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at),
    CONSTRAINT ck_broadcast_platform_sessions_ended
        CHECK (status NOT IN ('ENDED', 'FAILED') OR ended_at IS NOT NULL)
);

CREATE INDEX ix_broadcast_platform_sessions_parent_status
    ON broadcast_platform_sessions (broadcast_session_id, status);
CREATE INDEX ix_broadcast_platform_sessions_account_started
    ON broadcast_platform_sessions (platform_account_id, started_at DESC);
CREATE TRIGGER trg_broadcast_platform_sessions_updated_at
    BEFORE UPDATE ON broadcast_platform_sessions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

INSERT INTO broadcast_platform_sessions (
    broadcast_session_id, platform_account_id, status, started_at, ended_at,
    last_synced_at, created_at, updated_at
)
SELECT id, platform_account_id, status, started_at, ended_at,
       COALESCE(ended_at, started_at), created_at, updated_at
  FROM broadcast_sessions;

-- Rolling-deployment compatibility: an old application instance or a direct fixture that
-- inserts only the logical session still receives one representative child. The new service
-- uses the same unique key and reuses this row before adding any additional platform children.
CREATE OR REPLACE FUNCTION ensure_representative_platform_session()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO broadcast_platform_sessions (
        broadcast_session_id, platform_account_id, status,
        started_at, ended_at, last_synced_at
    ) VALUES (
        NEW.id, NEW.platform_account_id, NEW.status,
        NEW.started_at, NEW.ended_at, COALESCE(NEW.ended_at, NEW.started_at)
    )
    ON CONFLICT (broadcast_session_id, platform_account_id) DO NOTHING;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_broadcast_sessions_ensure_platform_child
    AFTER INSERT ON broadcast_sessions
    FOR EACH ROW EXECUTE FUNCTION ensure_representative_platform_session();

