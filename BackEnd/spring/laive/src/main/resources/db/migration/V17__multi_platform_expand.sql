    platform_account_id          BIGINT      PRIMARY KEY
        REFERENCES platform_accounts (id) ON DELETE CASCADE,
    auth_scheme                  VARCHAR(20) NOT NULL,
    encrypted_credential_payload TEXT        NOT NULL,
    encryption_key_version       VARCHAR(20) NOT NULL DEFAULT 'v1',
    access_expires_at            TIMESTAMPTZ,
    refresh_expires_at           TIMESTAMPTZ,
    scopes                       TEXT,
    credential_version           BIGINT      NOT NULL DEFAULT 1,
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_platform_credentials_auth_scheme
        CHECK (auth_scheme IN ('OAUTH2', 'API_KEY', 'CUSTOM')),
    CONSTRAINT ck_platform_credentials_version CHECK (credential_version > 0)
);

CREATE TRIGGER trg_platform_account_credentials_updated_at
    BEFORE UPDATE ON platform_account_credentials
