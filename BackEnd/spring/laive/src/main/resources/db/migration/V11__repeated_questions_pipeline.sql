-- =============================================================================
-- LAIVE - 1인 스트리머 AI 매니저
-- V11: 반복 질문 파이프라인 (AI/CHAT_AI_API.md §3)
--
-- V1의 repeated_questions는 폐기된 초안 계약(POST /internal/v1/ai/repeated-questions,
-- question + occurrence_count)을 위한 자리였다. 초안은 양측 모두 구현된 적 없이
-- 폐기됐고(명세 13.6 개정 2026-07-30), 확정 계약은 Spring이 chat-ai를
-- GET /broadcasts/{id}/questions 로 폴링해 저장하는 방식이다.
--
-- DROP & recreate인 이유
--   이 테이블에 쓰는 코드가 한 번도 존재하지 않아 모든 환경에서 빈 테이블이다.
--   설령 행이 있어도 초안 스키마에는 question_id가 없어 새 스키마로 변환할 수 없다.
--
-- 전량 교체 → UPSERT 전환 (V1 테이블 COMMENT와 V2 헤더의
-- "전량 교체된다" 설명은 이 마이그레이션으로 대체된다)
--   답변 완료(dismissed) 표식은 Spring만 기억한다 — AI의 집계는 Redis TTL 기반이라
--   재시작하면 지운 질문이 되살아난다. 폴링 결과로 행을 전량 교체하면 dismissed가
--   함께 날아가므로, (session_id, question_id) UPSERT로 반영하고 dismiss 관련
--   컬럼은 폴링이 절대 건드리지 않는다.
--
-- updated_at 트리거를 걸지 않는 이유
--   재질문 판정(아래 3컬럼)이 시각에 민감해 모든 쓰기 경로가 주입된 시각을
--   명시적으로 기록한다. 트리거의 now()가 이를 덮어쓰면 테스트에서 시각을
--   제어할 수 없다.
-- =============================================================================

DROP TABLE repeated_questions;

CREATE TABLE repeated_questions (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        BIGINT      NOT NULL REFERENCES broadcast_sessions (id) ON DELETE CASCADE,

    -- chat-ai가 발급하는 불투명 식별자. 16자리(집계 시작 epoch초 × 1,000,000
    -- + 시퀀스)라 BIGINT가 필수다. 형식은 바뀔 수 있으므로 값을 해석하지 말 것.
    question_id       BIGINT      NOT NULL,

    -- 같은 질문 묶음에서 가장 많이 쓰인 표현. 폴링마다 바뀔 수 있다.
    text              TEXT        NOT NULL,

    -- FAQ = 화면을 안 봐도 답할 수 있는 질문, CONTEXT = 지금 화면이 필요한 질문,
    -- NULL = 아직 판정 전. AI는 태그만 붙이고 거르지 않는다 — 필터는 프론트 몫.
    type              VARCHAR(10),

    askers            INT         NOT NULL,  -- 유니크 질문자 수. 정렬·재질문 판정 기준
    messages          INT         NOT NULL,  -- 총 메시지 수. askers와 벌어지면 도배 신호
    first_asked_at    TIMESTAMPTZ NOT NULL,  -- 첫 목격 시각. 폴링이 갱신하지 않는다
    last_asked_at     TIMESTAMPTZ NOT NULL,

    -- ---- 재질문 감지 3컬럼 (계약 §3 ①②③) ----
    -- ① dismiss: dismissed_at = now, askers_at_dismiss = 현재 askers, baseline = NULL
    -- ② 폴링마다: 유예(60초) 경과 후 baseline_askers 확정. 응답에 그 질문이 없으면
    --    askers_at_dismiss 로 확정한다(top-N 밖으로 밀리면 baseline이 영영 NULL이
    --    되는 문제의 fallback).
    -- ③ baseline 확정 후 askers - baseline >= 임계면 재노출. askers < baseline이면
    --    집계 리셋이므로 baseline을 현재값으로 낮추고 이번 판정은 건너뛴다.
    dismissed_at      TIMESTAMPTZ,           -- NULL = 콘솔 노출 중
    askers_at_dismiss INT,
    baseline_askers   INT,

    -- 재질문 감지로 다시 노출된 시각. NULL이 아니면 화면에 "재질문" 표식.
    -- 재차 dismiss해도 지우지 않는다 — 세션 리포트의 재질문 이력 근거로 남긴다.
    reexposed_at      TIMESTAMPTZ,

    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- UPSERT의 충돌 대상. (session_id, ...) 선두라 세션 내 조회도 커버하므로
    -- 별도 인덱스를 만들지 않는다 — 세션당 행 수가 최대 수백이라 세션을 좁힌 뒤
    -- askers DESC 정렬은 메모리에서 끝난다(V9 collection_gaps와 같은 판단).
    CONSTRAINT uq_repeated_questions_session_question UNIQUE (session_id, question_id),

    CONSTRAINT ck_repeated_questions_type
        CHECK (type IS NULL OR type IN ('FAQ', 'CONTEXT')),

    -- messages >= askers 는 의도적으로 검사하지 않는다. AI측 사소한 집계 버그
    -- 하나가 50행 벌크 UPSERT 트랜잭션 전체(재질문 판정 포함)를 죽이는 지점이 된다.
    CONSTRAINT ck_repeated_questions_counts CHECK (askers > 0 AND messages > 0),

    -- dismiss 세트 정합: dismissed_at 없이 부속 컬럼만 남을 수 없다
    CONSTRAINT ck_repeated_questions_dismiss
        CHECK (dismissed_at IS NOT NULL
               OR (askers_at_dismiss IS NULL AND baseline_askers IS NULL))
);

COMMENT ON TABLE  repeated_questions IS
    '세션의 반복 질문 누적 상태. chat-ai 폴링(AI/CHAT_AI_API.md §3)을 (session_id, question_id) UPSERT로 반영하고 dismissed를 보존한다 — 전량 교체 금지';
COMMENT ON COLUMN repeated_questions.question_id       IS 'chat-ai 발급 불투명 식별자(BIGINT 16자리). 폴링해도 안 바뀌고 재사용되지 않는다';
COMMENT ON COLUMN repeated_questions.text              IS '질문 묶음의 대표 표현. 폴링마다 갱신될 수 있다';
COMMENT ON COLUMN repeated_questions.type              IS 'FAQ / CONTEXT / NULL(판정 전). AI는 태그만 붙인다 — 필터는 프론트';
COMMENT ON COLUMN repeated_questions.askers            IS '유니크 질문자 수. 정렬 기준이자 재질문 판정의 입력';
COMMENT ON COLUMN repeated_questions.messages          IS '총 메시지 수. askers와 크게 벌어지면 한 명의 도배';
COMMENT ON COLUMN repeated_questions.first_asked_at    IS '첫 목격 시각. 불변 — 집계 리셋은 새 question_id로 온다';
COMMENT ON COLUMN repeated_questions.dismissed_at      IS '답변 완료 시각. NULL이면 콘솔 노출 중. 재노출 시 NULL로 되돌린다';
COMMENT ON COLUMN repeated_questions.askers_at_dismiss IS '답변 시점 askers. baseline 확정의 fallback(계약 §3 ②)';
COMMENT ON COLUMN repeated_questions.baseline_askers   IS '유예 종료 후 확정되는 재질문 판정 기준. NULL = 미확정';
COMMENT ON COLUMN repeated_questions.reexposed_at      IS '재질문 감지로 다시 노출된 시각. 재차 dismiss해도 보존한다';
