CREATE TABLE growth_roadmaps (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id           BIGINT       NOT NULL REFERENCES streamers (id) ON DELETE CASCADE,
    status                VARCHAR(30)  NOT NULL DEFAULT 'NOT_REQUESTED',
    quality               VARCHAR(20),
    current_generation_id BIGINT,
    source_report_id      BIGINT       REFERENCES reports (id) ON DELETE SET NULL,
    prompt_version        VARCHAR(100) NOT NULL,
    stale                 BOOLEAN      NOT NULL DEFAULT false,
    generated_at          TIMESTAMPTZ,
    generation_error      VARCHAR(100),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_growth_roadmaps_streamer UNIQUE (streamer_id),
    CONSTRAINT ck_growth_roadmaps_status CHECK (
        status IN ('NOT_REQUESTED', 'WAITING_FOR_DATA', 'PENDING',
                   'PROCESSING', 'READY', 'FAILED')
    ),
    CONSTRAINT ck_growth_roadmaps_quality CHECK (
        quality IS NULL OR quality IN ('INITIAL', 'ESTABLISHED')
    )
);

CREATE TABLE growth_roadmap_generations (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id        BIGINT       NOT NULL REFERENCES growth_roadmaps (id) ON DELETE CASCADE,
    source_report_id  BIGINT       REFERENCES reports (id) ON DELETE SET NULL,
    trigger_type      VARCHAR(30)  NOT NULL,
    status            VARCHAR(30)  NOT NULL,
    quality           VARCHAR(20)  NOT NULL,
    prompt_version    VARCHAR(100) NOT NULL,
    idempotency_key   VARCHAR(220) NOT NULL,
    input_fingerprint VARCHAR(64),
    requested_at      TIMESTAMPTZ  NOT NULL,
    started_at        TIMESTAMPTZ,
    completed_at      TIMESTAMPTZ,
    error_code        VARCHAR(100),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_growth_roadmap_generation_key UNIQUE (idempotency_key),
    CONSTRAINT ck_growth_roadmap_generation_trigger CHECK (
        trigger_type IN ('FIRST_REPORT', 'THIRD_REPORT', 'REPORT_COMPLETED',
                         'PORTFOLIO_UPDATED', 'PROMPT_VERSION_CHANGED', 'MANUAL')
    ),
    CONSTRAINT ck_growth_roadmap_generation_status CHECK (
        status IN ('WAITING_FOR_DATA', 'PENDING', 'PROCESSING',
                   'COMPLETED', 'FAILED', 'SUPERSEDED')
    ),
    CONSTRAINT ck_growth_roadmap_generation_quality CHECK (
        quality IN ('INITIAL', 'ESTABLISHED')
    )
);

ALTER TABLE growth_roadmaps
    ADD CONSTRAINT fk_growth_roadmaps_current_generation
        FOREIGN KEY (current_generation_id)
        REFERENCES growth_roadmap_generations (id) ON DELETE SET NULL;

CREATE TABLE growth_goal_suggestions (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id       BIGINT        NOT NULL REFERENCES growth_roadmaps (id) ON DELETE CASCADE,
    generation_id    BIGINT        NOT NULL REFERENCES growth_roadmap_generations (id) ON DELETE CASCADE,
    display_order    INT           NOT NULL,
    metric_type      VARCHAR(30)   NOT NULL,
    target_value     NUMERIC(12,2) NOT NULL,
    unit             VARCHAR(20)   NOT NULL,
    period_start     DATE          NOT NULL,
    period_end       DATE          NOT NULL,
    title            VARCHAR(200)  NOT NULL,
    rationale        TEXT          NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'SUGGESTED',
    accepted_goal_id BIGINT        REFERENCES growth_goals (id) ON DELETE SET NULL,
    accepted_at      TIMESTAMPTZ,
    dismissed_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_growth_suggestions_order UNIQUE (generation_id, display_order),
    CONSTRAINT uq_growth_suggestions_metric UNIQUE (generation_id, metric_type),
    CONSTRAINT ck_growth_suggestions_order CHECK (display_order BETWEEN 1 AND 3),
    CONSTRAINT ck_growth_suggestions_metric CHECK (
        metric_type IN ('AVG_VIEWERS', 'BROADCASTS_PER_WEEK',
                        'TOTAL_CHAT', 'BROADCAST_MINUTES')
    ),
    CONSTRAINT ck_growth_suggestions_status CHECK (
        status IN ('SUGGESTED', 'ACCEPTED', 'DISMISSED', 'SUPERSEDED')
    ),
    CONSTRAINT ck_growth_suggestions_period CHECK (period_end >= period_start),
    CONSTRAINT ck_growth_suggestions_target CHECK (target_value > 0)
);

CREATE TABLE growth_suggestion_actions (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suggestion_id BIGINT       NOT NULL REFERENCES growth_goal_suggestions (id) ON DELETE CASCADE,
    display_order INT          NOT NULL,
    title         VARCHAR(200) NOT NULL,
    content       TEXT         NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_growth_suggestion_actions_order UNIQUE (suggestion_id, display_order),
    CONSTRAINT ck_growth_suggestion_actions_order CHECK (display_order BETWEEN 1 AND 3)
);

ALTER TABLE growth_actions
    ADD COLUMN source_suggestion_id BIGINT
        REFERENCES growth_goal_suggestions (id) ON DELETE SET NULL,
    ADD CONSTRAINT ck_growth_actions_single_source CHECK (
        generation_id IS NULL OR source_suggestion_id IS NULL
    );

CREATE INDEX ix_growth_roadmap_generations_roadmap_requested
    ON growth_roadmap_generations (roadmap_id, requested_at DESC, id DESC);
CREATE INDEX ix_growth_roadmap_generations_pending
    ON growth_roadmap_generations (status, requested_at)
    WHERE status = 'PENDING';
CREATE INDEX ix_growth_suggestions_roadmap_status
    ON growth_goal_suggestions (roadmap_id, status, display_order);
CREATE INDEX ix_growth_suggestion_actions_suggestion
    ON growth_suggestion_actions (suggestion_id, display_order);
CREATE INDEX ix_growth_actions_source_suggestion
    ON growth_actions (source_suggestion_id);

CREATE TRIGGER trg_growth_roadmaps_updated_at
    BEFORE UPDATE ON growth_roadmaps
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_growth_roadmap_generations_updated_at
    BEFORE UPDATE ON growth_roadmap_generations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

